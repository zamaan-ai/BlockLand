import { Router } from 'express';
import { authenticate, requireRole } from '../middleware/auth';
import * as controller from '../controllers/dashboard.controller';
import * as roleController from '../controllers/role-dashboard.controller';
const router = Router();
router.use(authenticate);
router.get('/user', requireRole('USER', 'LANDOWNER', 'BUYER'), controller.getUserDashboard);
router.get('/owner', requireRole('LANDOWNER', 'USER'), roleController.getOwnerDashboard);
router.get('/buyer', requireRole('BUYER', 'USER'), roleController.getBuyerDashboard);
router.get('/developer', requireRole('DEVELOPER'), roleController.getDeveloperDashboard);
router.get('/government', requireRole('GOVERNMENT', 'ADMIN'), roleController.getOfficerDashboard);
router.get('/officer', requireRole('GOVERNMENT', 'ADMIN'), roleController.getOfficerDashboard);
router.get('/roles', roleController.getRoleOptions);
router.post('/developer-role-request', requireRole('USER', 'LANDOWNER', 'BUYER'), roleController.requestDeveloperRole);
router.patch('/developer/profile', requireRole('DEVELOPER'), roleController.updateDeveloperProfile);
router.post('/objections/:plotId', roleController.submitPublicObjection);
router.post('/objections/:objectionId/resolve', requireRole('GOVERNMENT', 'ADMIN'), roleController.resolvePublicObjection);
router.post('/encumbrances/:encumbranceId/clear', requireRole('GOVERNMENT', 'ADMIN'), roleController.clearEncumbrance);
router.post('/disputes/:disputeId/resolve', requireRole('GOVERNMENT', 'ADMIN'), roleController.resolveDispute);
router.post('/fraud-flags/:flagId/resolve', requireRole('GOVERNMENT', 'ADMIN'), roleController.resolveFraudFlag);
router.get('/second-approvals', requireRole('GOVERNMENT', 'ADMIN'), roleController.getHighRiskTransfers);
router.post('/watchlist/:plotId', requireRole('BUYER', 'LANDOWNER', 'USER'), roleController.saveProperty);
router.delete('/watchlist/:plotId', requireRole('BUYER', 'LANDOWNER', 'USER'), roleController.removeSavedProperty);
router.post('/developers/:userId/follow', requireRole('BUYER', 'LANDOWNER', 'USER'), roleController.followDeveloper);
router.delete('/developers/:userId/follow', requireRole('BUYER', 'LANDOWNER', 'USER'), roleController.unfollowDeveloper);
router.get('/notifications', controller.getNotifications);
router.post('/transfers/:transferId/verify-buyer', requireRole('GOVERNMENT', 'ADMIN'), controller.verifyBuyer);
router.post('/encumbrances', requireRole('GOVERNMENT', 'ADMIN'), controller.createEncumbrance);
router.post('/disputes', requireRole('GOVERNMENT', 'ADMIN'), controller.createDispute);
router.post('/fraud-flags', controller.createFraudFlag);
router.post('/owner/freeze/:landId', requireRole('LANDOWNER', 'USER'), controller.freezeLandTransfers);
router.post('/owner/unfreeze/:landId', requireRole('LANDOWNER', 'USER'), controller.unfreezeLandTransfers);
export default router;
